import fs from 'node:fs';
import crypto from 'node:crypto';
import Database from 'better-sqlite3';
import { writeJson } from '../core/jsonl.js';
import type { MirrorSession } from './types.js';
import path from 'node:path';
import { AMUX_HOME } from '../core/paths.js';

const STATE_FILE = path.join(AMUX_HOME, 'mirror-state.json');

interface Verification {
  fingerprint?: string;
  nativeReadbackVerifiedAt?: number;
  nativeStorageVersion?: number;
}

interface MirrorTargetInfo extends Verification {
  agent: 'codex' | 'antigravity';
  sourceId: string;
  turnCount: number;
  createdAt: number;
}

interface SourceSyncInfo extends Verification {
  targetAgent: 'codex' | 'antigravity';
  targetSessionId: string;
  turnCount: number;
  updatedAt: number;
}

interface PersistentState {
  mirroredTargets: Record<string, MirrorTargetInfo>;
  sourceSyncMap: Record<string, SourceSyncInfo>;
}

function loadState(): PersistentState {
  if (!fs.existsSync(STATE_FILE)) return { mirroredTargets: {}, sourceSyncMap: {} };
  const state = JSON.parse(fs.readFileSync(STATE_FILE, 'utf8')) as PersistentState;
  if (!state.mirroredTargets || !state.sourceSyncMap) throw new Error('amux 镜像状态格式无效');
  return state;
}

export function sessionFingerprint(session: MirrorSession): string {
  return crypto.createHash('sha256').update(JSON.stringify(session.turns.map(({ role, text }) => ({ role, text })))).digest('hex');
}

/** Check if a given sessionId was generated by amux as a mirror destination */
export function isMirrorTarget(sessionId: string): boolean {
  const state = loadState();
  return Boolean(state.mirroredTargets[sessionId]);
}

/** Record a new mirror target generated by amux */
export function recordMirrorTarget(
  targetSessionId: string,
  targetAgent: 'codex' | 'antigravity',
  sourceSessionId: string,
  turnCount: number,
  verification: Verification = {}
): void {
  fs.mkdirSync(AMUX_HOME, { recursive: true });
  const lock = new Database(path.join(AMUX_HOME, 'state-lock.sqlite'), { timeout: 5000 });
  try {
    lock.exec('BEGIN IMMEDIATE');
    const state = loadState();
    const now = Date.now();

    state.mirroredTargets[targetSessionId] = {
      agent: targetAgent,
      sourceId: sourceSessionId,
      turnCount,
      createdAt: now,
      ...verification,
    };
    state.sourceSyncMap[sourceSessionId] = {
      targetAgent,
      targetSessionId,
      turnCount,
      updatedAt: now,
      ...verification,
    };
    writeJson(STATE_FILE, state);
    lock.exec('COMMIT');
  } finally { lock.close(); }
}

/** Get the last sync info for a source session */
export function getLastSync(sourceSessionId: string): SourceSyncInfo | null {
  const state = loadState();
  return state.sourceSyncMap[sourceSessionId] || null;
}
